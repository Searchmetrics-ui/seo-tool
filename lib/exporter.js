/**
 * Report Exporter
 * Generates Markdown, JSON, and text audit reports.
 */

function generateMarkdownReport(auditResult) {
  const { url, title, targetQuery, geoIndex, tier, pillars, checklist, simulator, rewrites } = auditResult;

  let md = `# GeoPulse AEO & GEO Audit Report
**Target URL:** ${url}  
**Page Title:** ${title}  
**Target Query:** ${targetQuery || 'N/A'}  
**Generated At:** ${new Date().toISOString()}  

---

## 🏆 Total GEO Visibility Index: ${geoIndex}/100 (${tier})

### Core Scoring Pillars:
- **Direct Answerability (AEO):** ${pillars.directAnswer}%
- **Statistical Density (GEO):** ${pillars.statsDensity}%
- **Authoritative Quotations:** ${pillars.quoteAttribution}%
- **AI Crawler & Schema Readiness:** ${pillars.aiReadiness}%
- **RAG Chunkability:** ${pillars.chunkability}%

---

## 🤖 AI Search Engine Citation Probability:
- **Perplexity Pro:** ${simulator.probabilities.perplexity}%
- **ChatGPT Search:** ${simulator.probabilities.chatgpt}%
- **Google AI Overview:** ${simulator.probabilities.gemini}%
- **Claude Search:** ${simulator.probabilities.claude}%

---

## 📋 Priority Actionable Fix Checklist:
`;

  checklist.forEach(item => {
    md += `\n### [${item.severity}] ${item.title}\n`;
    md += `- **Category:** ${item.category}\n`;
    md += `- **Detail:** ${item.detail}\n`;
    if (item.recommendation) {
      md += `- **Recommendation:** ${item.recommendation}\n`;
    }
  });

  md += `\n---

## ✍️ AI-Optimized Content Rewrites:
`;

  rewrites.forEach(r => {
    md += `\n### ${r.title}\n`;
    md += `**Rationale:** ${r.rationale}\n\n`;
    md += `**Original:**\n> ${r.original}\n\n`;
    md += `**Optimized (Recommended GEO Format):**\n> ${r.optimized}\n\n`;
  });

  md += `\n---\n*Report generated by GeoPulse — Answer Engine Optimization & Generative Search Intelligence Suite.*`;

  return md;
}

module.exports = { generateMarkdownReport };
